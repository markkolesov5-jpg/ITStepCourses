# Проводиться опитування «Чи потрібно будувати більше
# дитячих садків у вашому місті?»
# Напишіть програму для підрахунку відповідей.
# Користувач вводить слова «так» або «ні» поки не введе
# слово «стоп», після чого треба показати кількості «так» та
# «ні» і також яких голосів більше.
# Якщо введено невідоме слово, то вивести повідомлення
# про помилку та продовжити підрахунок
count_tak = 0
count_ni = 0
while True:
  answer = input(
      "«Чи потрібно будувати більше дитячих садків у вашому місті дайте відповідь"
      " так/ні ?» "
  )

  if answer == "стоп":
    break
  elif answer == "так":
    count_tak = count_tak + 1
  elif answer == "ні":
    count_ni = count_ni + 1
  else:
    print("Помилка")

print("\n--- Результати опитування ---")
print("Кількість голосів «так»:", count_tak)
print("Кількість голосів «ні»:", count_ni)

if count_tak > count_ni:
  print("Результат: голосів «так» більше.")
elif count_ni > count_tak:
  print("Результат: голосів «ні» більше.")
else:
  print("Результат: кількість голосів «так» та «ні» однакова.")
