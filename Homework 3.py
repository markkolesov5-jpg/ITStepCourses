#Троє друзів пішли на рибалку. Програма отримує
#кількість риби яку зловив кожен рибалка.
#Виведіть на екран:
#● скільки в середньому вийшло риб на людину
#● розмір найбільшого улову
fish_1 = int(input('Введіть кількість риби першого рибалки:'))
fish_2 = int(input("Введіть кільлкість риби другого рибалки:"))
fish_3 = int(input("Введіть кількість риби третього рибалки: "))

average = (fish_1 + fish_2 + fish_3) // 3

max_catch = max(fish_1, fish_2, fish_3)

print(f"В середньому на людину вийшло риб: {average}")
print(f"Розмір найбільшого улову: {max_catch}")

