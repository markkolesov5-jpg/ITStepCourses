#товару. Якщо загальна сума більша за 500грн або купівля
#оптом(більше 10 шт), застосувати знижку 10%
from pydoc import Helper

price = float(input("Введіть ціну товару:"))
quantity = int(input("Введіть кількість товару:"))

amount = price * quantity

if amount > 500 or quantity > 10:
    discount =  amount * 0.10
    result = amount - discount
    print(f"До сплати зі знижкою {result} грн ")

else:
    print(f"До сплати {amount} грн")


